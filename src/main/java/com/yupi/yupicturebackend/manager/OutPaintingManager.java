package com.yupi.yupicturebackend.manager;

import cn.hutool.http.HttpResponse;
import cn.hutool.http.HttpUtil;
import cn.hutool.json.JSONObject;
import cn.hutool.json.JSONUtil;
import com.yupi.yupicturebackend.config.AiConfig;
import com.yupi.yupicturebackend.exception.BusinessException;
import com.yupi.yupicturebackend.exception.ErrorCode;
import com.yupi.yupicturebackend.exception.ThrowUtils;
import com.yupi.yupicturebackend.model.vo.PictureExpandResultVO;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import javax.annotation.Resource;
import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;

/**
 * 阿里云百炼「图像画面扩展」客户端（docs/adr/0010）
 * <p>
 * 异步两段：submit 创建任务拿 taskId，query 轮询任务状态；后端不持有任务状态。
 *
 * @author SPHZ
 */
@Service
@Slf4j
public class OutPaintingManager {

    private static final String SUBMIT_PATH = "/api/v1/services/aigc/image2image/out-painting";

    private static final String TASK_PATH = "/api/v1/tasks/";

    private static final int TIMEOUT_MS = 15000;

    /**
     * output_ratio 的实测白名单。服务端拒绝时会把可选项原样列出来：
     * "the output_ratio(1.0) is error, please choose one from ['', '1:1', '3:4', '4:3', '9:16', '16:9']"
     * （2026-09-25 实测，含设备屏幕常见的 16:10）。白名单外的比例只能改走像素偏移。
     */
    private static final Set<String> PROVIDER_RATIOS = new HashSet<>(Arrays.asList("1:1", "4:3", "3:4", "16:9", "9:16"));

    @Resource
    private AiConfig aiConfig;

    /**
     * 提交扩图任务
     *
     * @param imageUrl     可公网访问的原图地址
     * @param outputRatio  目标宽高比，如 16:9；白名单外（如 16:10）自动改走像素偏移
     * @param sourceWidth  原图宽（像素偏移需要，白名单比例可为空）
     * @param sourceHeight 原图高
     * @return 任务 id
     */
    public String submitExpandTask(String imageUrl, String outputRatio, Integer sourceWidth, Integer sourceHeight) {
        // add_watermark 官方默认 true，会在输出图左下角打 "Generated by AI" 水印，必须显式关闭
        JSONObject parameters = JSONUtil.createObj().set("add_watermark", false);
        if (PROVIDER_RATIOS.contains(outputRatio)) {
            parameters.set("output_ratio", outputRatio);
        } else {
            fillOffsetParameters(parameters, outputRatio, sourceWidth, sourceHeight);
        }
        JSONObject body = JSONUtil.createObj()
                .set("model", aiConfig.getOutpainting().getModel())
                .set("input", JSONUtil.createObj().set("image_url", imageUrl))
                .set("parameters", parameters);
        HttpResponse response = HttpUtil.createPost(aiConfig.getOutpainting().getBaseUrl() + SUBMIT_PATH)
                .header("Authorization", "Bearer " + aiConfig.getOutpainting().getApiKey())
                .header("X-DashScope-Async", "enable")
                .header("Content-Type", "application/json")
                .body(body.toString())
                .timeout(TIMEOUT_MS)
                .execute();
        JSONObject result = JSONUtil.parseObj(response.body());
        String errorCode = result.getStr("code");
        if (errorCode != null) {
            log.error("扩图任务提交失败, code={}, message={}", errorCode, result.getStr("message"));
            throw new BusinessException(ErrorCode.OPERATION_ERROR, mapErrorMessage(errorCode));
        }
        String taskId = result.getByPath("output.task_id", String.class);
        ThrowUtils.throwIf(taskId == null || taskId.isBlank(), ErrorCode.OPERATION_ERROR, "扩图服务返回异常");
        return taskId;
    }

    /**
     * 把目标比例换算成四边各补多少像素（白名单外的比例走这条路）。
     * 偏移只能加不能减，所以永远沿"需要变长的那条边"补：目标更宽就补宽，目标更高就补高。
     * 2026-09-25 实测：3640×2048 传 top 113 / bottom 114 → 3640×2275，正是精确的 16:10。
     */
    private void fillOffsetParameters(JSONObject parameters, String outputRatio,
                                      Integer sourceWidth, Integer sourceHeight) {
        ThrowUtils.throwIf(sourceWidth == null || sourceHeight == null || sourceWidth <= 0 || sourceHeight <= 0,
                ErrorCode.OPERATION_ERROR, "该图片缺少尺寸信息，暂不支持自定义画幅");
        double targetRatio;
        try {
            int colon = outputRatio.indexOf(':');
            double width = Double.parseDouble(outputRatio.substring(0, colon));
            double height = Double.parseDouble(outputRatio.substring(colon + 1));
            targetRatio = width / height;
        } catch (RuntimeException e) {
            throw new BusinessException(ErrorCode.PARAMS_ERROR, "不支持的宽高比");
        }
        ThrowUtils.throwIf(!(targetRatio > 0), ErrorCode.PARAMS_ERROR, "不支持的宽高比");
        double sourceRatio = sourceWidth * 1.0 / sourceHeight;
        // 与 output_ratio 同一条规则：目标画幅不能与原图相同，相同就没有要补的边界
        ThrowUtils.throwIf(Math.abs(targetRatio - sourceRatio) / sourceRatio < 0.001,
                ErrorCode.PARAMS_ERROR, "目标画幅不能与原图相同，请换一个比例");
        if (targetRatio > sourceRatio) {
            int delta = Math.max(1, (int) Math.round(sourceHeight * targetRatio) - sourceWidth);
            // 官方上限是单轴合计 < 3× 输入边长，这里按同一口径挡掉离谱请求
            ThrowUtils.throwIf(delta >= sourceWidth * 3, ErrorCode.PARAMS_ERROR, "目标画幅超出可扩展范围");
            parameters.set("left_offset", delta / 2).set("right_offset", delta - delta / 2);
        } else {
            int delta = Math.max(1, (int) Math.round(sourceWidth / targetRatio) - sourceHeight);
            ThrowUtils.throwIf(delta >= sourceHeight * 3, ErrorCode.PARAMS_ERROR, "目标画幅超出可扩展范围");
            parameters.set("top_offset", delta / 2).set("bottom_offset", delta - delta / 2);
        }
    }

    /**
     * 查询扩图任务状态
     *
     * @param taskId 任务 id
     * @return 任务状态与结果图地址（成功时）
     */
    public PictureExpandResultVO queryExpandTask(String taskId) {
        HttpResponse response = HttpUtil.createGet(aiConfig.getOutpainting().getBaseUrl() + TASK_PATH + taskId)
                .header("Authorization", "Bearer " + aiConfig.getOutpainting().getApiKey())
                .timeout(TIMEOUT_MS)
                .execute();
        JSONObject result = JSONUtil.parseObj(response.body());
        String errorCode = result.getStr("code");
        if (errorCode != null) {
            log.error("扩图任务查询失败, taskId={}, code={}", taskId, errorCode);
            throw new BusinessException(ErrorCode.OPERATION_ERROR, mapErrorMessage(errorCode));
        }
        PictureExpandResultVO vo = new PictureExpandResultVO();
        vo.setStatus(result.getByPath("output.task_status", String.class));
        vo.setImageUrl(result.getByPath("output.output_image_url", String.class));
        if ("FAILED".equals(vo.getStatus())) {
            String failCode = result.getByPath("output.code", String.class);
            // 服务端 FAILED 不走异常路径，不在这里落日志就再也查不到失败原因
            log.error("扩图任务失败, taskId={}, code={}, message={}", taskId, failCode,
                    result.getByPath("output.message", String.class));
            vo.setMessage(mapErrorMessage(failCode));
        }
        return vo;
    }

    /**
     * 百炼错误码 → 中文提示
     */
    private String mapErrorMessage(String code) {
        if (code == null) {
            return "扩图服务暂时不可用，请稍后重试";
        }
        switch (code) {
            case "Arrearage":
                return "阿里云账户欠费或服务未开通，请联系管理员";
            // 目标画幅与原图一致：服务端不扩、直接判 FAILED（见 docs/adr/0010）
            case "InvalidParameter.ImageResolution":
                return "目标画幅不能与原图相同，请换一个比例";
            case "InvalidParameter":
            case "InvalidURL":
                return "扩图参数不合法";
            case "Throttling":
            case "Throttling.User":
                return "扩图请求过于频繁，请稍后再试";
            case "AccessDenied":
                return "无权调用扩图服务";
            case "InvalidTask":
            case "TaskNotFound":
                return "任务已过期，请重新发起";
            default:
                // 错误码带子类后缀（InvalidParameter.Xxx）时别落进兜底文案，否则用户看到的是"服务不可用"
                return code.startsWith("InvalidParameter.") ? "扩图参数不合法" : "扩图服务暂时不可用，请稍后重试";
        }
    }
}
